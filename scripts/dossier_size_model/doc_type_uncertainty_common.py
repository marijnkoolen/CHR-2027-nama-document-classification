"""
Shared infrastructure for propagating document-type classifier uncertainty
into the dossier_size_model per-document-type analyses (doc_type_three_groups,
doc_type_count_vs_presence). Those analyses used the TSV's per-type counts
as ground truth; those counts were themselves generated by the same
classifier with the same uneven per-type precision/recall corrected for in
scripts/dossier_composition/. This module joins the two datasets and reuses
the confusion matrix already fit there (same classifier, same test set --
no need to refit it).

Scope note: this only applies to per-document-TYPE outcomes. The aggregate
num_docs models (model_dossier_size*.py) use total segment counts, which are
insensitive to document-type misclassification (only to segmentation/
start-page errors, a different, uncorrected uncertainty source) -- they are
out of scope here.

Two correction modes, both operating on the SAME 1307-dossier subset used
throughout dossier_size_model (joined to the full predicted corpus by
matching each dossier's numeric identifier to its pdf_name suffix -- verified
as a clean 1-to-1 join, 1309/1309 dossiers, before relying on it):

  point -- fast, CPU-runnable (no GPU needed). Deconvolves each dossier's
           segment-level predictions into EXPECTED (fractional) per-type
           counts using the DOCUMENT-TYPE confusion matrix's POSTERIOR MEAN.
           Corrects the average type-confusion bias, but its credible
           intervals still understate true uncertainty -- it propagates the
           classifier's point estimate, not its own uncertainty. Fits a
           negative-binomial likelihood to non-integer "observed" counts,
           which PyMC accepts (the NB log-density is defined via gamma
           functions for non-integer inputs) but is a deliberate
           approximation -- flagged wherever this mode's results are used.
           Segmentation (start_page) is held at its predicted boundaries in
           this mode -- deconvolving "expected number of segments" the same
           way isn't a simple per-page reweighting (segment boundaries are
           structural, not a soft label), and the start_page classifier is
           reliable enough (84.4%/97.9% precision/recall) that this is a
           minor simplification for a mode that's explicitly the fast/
           approximate one. Only `mi` corrects segmentation.

  mi    -- rigorous, and the one that matters: corrects BOTH document-type
           confusion AND segmentation (start_page) uncertainty jointly.
           Reuses dossier_composition/imputation.py's
           sample_segments_for_draw (built and validated there first) --
           each draw resamples start_page per page from the 2-class
           confusion matrix, rebuilds segment boundaries from that, majority-
           votes and resamples type on the NEW segments -- rather than
           duplicating that resegmentation logic here. Refits the regression
           per imputation, pools posteriors across imputations -- proper
           multiple imputation, at GPU-scale imputation counts. See
           doc_type_three_groups_uncertainty.py's docstring for the GPU
           setup (not runnable at practical scale on CPU).

           mi-mode output filenames carry a `joint` tag (idata_mi_joint_...,
           not idata_mi_...) specifically so they can never collide with or
           be silently skipped in favor of checkpoints from the EARLIER
           type-only version of this pipeline (before segmentation
           correction existed) -- if you have old idata_mi_{period}_{k}.nc
           files from that version sitting in the output dir, they're now
           orphaned, not reused; delete them or rerun to get joint-corrected
           results, don't mix them into a `pool` alongside the new ones.
"""

